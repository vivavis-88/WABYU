<?php
declare(strict_types=1);
/**
 * One-time setup (command line only): creates config/secrets.php with password HASHES.
 *   php setup.php
 */
if (PHP_SAPI !== 'cli') { http_response_code(404); exit; }
require_once __DIR__ . '/includes/storage.php';

function ask(string $prompt): string
{
    echo $prompt;
    if (stripos(PHP_OS_FAMILY, 'Windows') === false && function_exists('shell_exec')) {
        shell_exec('stty -echo'); $v = trim((string)fgets(STDIN)); shell_exec('stty echo'); echo "\n"; return $v;
    }
    return trim((string)fgets(STDIN));   // Windows: input is visible while typing
}

$target = __DIR__ . '/config/secrets.php';
if (is_file($target)) {
    echo "config/secrets.php already exists.\nType YES to replace the passwords, or anything else to keep them: ";
    if (trim((string)fgets(STDIN)) !== 'YES') { echo "Nothing changed.\n"; exit(0); }
}
echo "\nWABYU setup\n-----------\n";
do {
    $login = ask("Choose your login password (at least 8 characters): ");
    if (strlen($login) < 8) { echo "Too short, try again.\n"; }
} while (strlen($login) < 8);

$delete = ask("Deletion confirmation password [press Enter to use YESCONFIRM]: ");
if ($delete === '') { $delete = 'YESCONFIRM'; }

$php = "<?php\n// Generated by setup.php on " . gmdate('c') . ". Contains password hashes only. Never commit this file.\nreturn " . var_export([
    'login_hash'  => password_hash($login, PASSWORD_DEFAULT),
    'delete_hash' => password_hash($delete, PASSWORD_DEFAULT),
], true) . ";\n";
wabyu_init_storage();
if (file_put_contents($target, $php, LOCK_EX) === false) { fwrite(STDERR, "Could not write config/secrets.php\n"); exit(1); }
echo "\nDone. config/secrets.php created and storage folders initialised.\nOpen http://localhost/wabyu/ in your browser.\n";
